"""Generate the browsable taxonomy from the single packaged JSON catalogue.

Run from any working directory: python scripts/build_catalog.py [--check].
No network or optional dependencies are used.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOGUE = ROOT / "src/mop_problems/data/catalog.json"
NOTICE = "<!-- Generated by scripts/build_catalog.py; edit the source catalogue instead. -->\n"


def link(source: Path, target: Path) -> str:
    return Path(os.path.relpath(target, source.parent)).as_posix()


def render() -> dict[Path, str]:
    data = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    documents = {}
    suites = data["suites"]
    problems = data["problems"]
    index = ROOT / "problems/README.md"
    lines = [
        NOTICE,
        "# Problem catalogue / 问题目录",
        "",
        f"{len(suites)} catalogue entries; **{len(problems)} callable problems**. "
        "`planned` means documentation only, with no Python implementation.",
        "",
        "完整保留原始分类。`planned` 为待实现条目，不会返回替代函数或占位数值。",
        "",
        "| Suite / 问题族 | Category | Status | Callable |",
        "| --- | --- | --- | ---: |",
    ]
    for suite in suites:
        target = ROOT / suite["path"] / "README.md"
        members = [p for p in problems if p["suite"] == suite["id"]]
        lines.append(
            f"| [{suite['name']}]({link(index, target)}) | `{suite['category']}` "
            f"| {suite['status']} | {len(members)} |"
        )
        content = [
            NOTICE,
            f"# {suite['name']}",
            "",
            f"**Status / 状态: {suite['status']}**",
            "",
            f"Category: `{suite['category']}`",
            "",
            suite["notes"],
            "",
            f"Source status: `{suite['source_status']}`. "
            "Identifying a source is separate from validating an implementation.",
            "",
            "## Reference / 来源",
            "",
            suite["reference"],
            "",
        ]
        if suite["source_url"]:
            content += [f"[Source / 参考来源]({suite['source_url']})", ""]
        else:
            content += ["Original source pending verification / 原始来源待核对。", ""]
        content += ["## Members / 成员", ""]
        if members:
            content += [
                "| Problem | Default variables | Default objectives | Inequalities | "
                "Equalities | Analytical PF sampler |",
                "| --- | ---: | ---: | ---: | ---: | --- |",
            ]
            for p in members:
                name = p["name"]
                details = ROOT / suite["path"] / name / "README.md" if len(members) > 1 else target
                label = f"[{name}]({link(target, details)})" if details != target else name
                content.append(
                    f"| {label} | {p['n_var']} | {p['n_obj']} | {p['n_ieq_constr']} "
                    f"| {p['n_eq_constr']} | {'yes' if p['pareto_front'] else 'no'} |"
                )
                implementation = p["implementation"].split(":")[0].replace(".", "/") + ".py"
                detail_lines = [
                    f"## {name}: implementation details",
                    "",
                    f"[Python formula]({link(details, ROOT / 'src' / implementation)}) · "
                    f"[Mathematical definition]({link(details, ROOT / 'docs/formulas.md')}"
                    f"#{name.lower()})",
                    "",
                    f"- Decision bounds: `{p['lower_bounds']}` to `{p['upper_bounds']}` "
                    "(scalar bounds broadcast to all variables).",
                    f"- Default parameters: `{json.dumps(p['parameters'])}`.",
                    f"- Properties: {', '.join(p['properties'])}.",
                    "- All objectives are minimized; constraints use `G <= 0`, `H = 0`.",
                    f"- Notes: {p['notes'] or 'See the common API contract.'}",
                    "",
                    "```python",
                    "from mop_problems import get_problem",
                    "",
                    f'problem = get_problem("{name}")',
                    "result = problem.evaluate(problem.sample(4, seed=42))",
                    "print(result.F)",
                    "```",
                    "",
                ]
                if details != target:
                    documents[details] = "\n".join(
                        [
                            NOTICE,
                            f"# {name}",
                            "",
                            "**Status: implemented**",
                            "",
                            f"[Family and references]({link(details, target)})",
                            "",
                            *detail_lines,
                        ]
                    )
                else:
                    content += ["", *detail_lines]
        else:
            content += [
                ("Target members: " + ", ".join(f"`{x}`" for x in suite["members"]))
                if suite["members"]
                else "Member list pending source/version verification.",
                "",
                "These are target catalogue entries, **not callable problems**.",
                "",
                "Before implementation: verify the original definition/version, variable "
                "types and bounds, objective directions, constraints, and reference outputs. "
                "Add numerical tests before registering a callable implementation.",
                "",
            ]
        content += ["", f"[Full catalogue]({link(target, index)})", ""]
        documents[target] = "\n".join(content)
    documents[index] = "\n".join([*lines, ""])
    # Every directory level can be browsed on GitHub without an empty placeholder.
    for category in sorted(
        {s["category"] for s in suites} | {s["category"].split("/")[0] for s in suites}
    ):
        page = ROOT / "problems" / category / "README.md"
        selected = [
            s
            for s in suites
            if s["category"] == category or s["category"].startswith(category + "/")
        ]
        body = [NOTICE, f"# {category}", "", f"[Full catalogue]({link(page, index)})", ""]
        for s in selected:
            body.append(
                f"- [{s['name']}]({link(page, ROOT / s['path'] / 'README.md')}) — **{s['status']}**"
            )
        documents[page] = "\n".join([*body, ""])
    return documents


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of updating stale files")
    args = parser.parse_args()
    stale = []
    for path, expected in render().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == expected:
            continue
        stale.append(path.relative_to(ROOT).as_posix())
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    if args.check and stale:
        print("Catalogue pages are stale:\n" + "\n".join(stale))
        return 1
    print(f"Catalogue {'checked' if args.check else 'generated'}: {len(render())} pages.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
